import { chromium } from 'playwright';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';

const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1100},locale:'ru-RU'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await mkdir('test-results',{recursive:true});
try{
 let releaseSession;
 const sessionGate=new Promise(resolve=>{releaseSession=resolve;});
 await page.route('**/api/auth/session/',async route=>{await sessionGate;await route.continue();});
 await page.goto('http://localhost:3000');
 await page.getByRole('status',{name:'Загрузка данных'}).waitFor();
 await page.screenshot({path:'test-results/skeleton.png',fullPage:true,animations:'disabled'});
 releaseSession();
 await page.unrouteAll({behavior:'wait'});
 await page.getByRole('button',{name:'Открыть локальную версию'}).click();
 await page.getByRole('heading',{name:'Твои подписки.'}).waitFor();
 assert.equal(await page.locator('.family-card').count(),3);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'test-results/desktop-light.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Включить тёмную тему'}).click();
 await page.screenshot({path:'test-results/desktop-dark.png',fullPage:true,animations:'disabled'});
 await page.reload();
 await page.getByRole('heading',{name:'Твои подписки.'}).waitFor();
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.getByRole('button',{name:'Включить светлую тему'}).click();
 await page.getByRole('combobox',{name:'Валюта отображения'}).selectOption('USD');
 await page.waitForResponse(r=>r.url().includes('/api/overview/?currency=USD')&&r.ok());
 await page.getByRole('combobox',{name:'Валюта отображения'}).selectOption('BYN');
 await page.waitForResponse(r=>r.url().includes('/api/overview/?currency=BYN')&&r.ok());
 await page.locator('.nav-item').filter({hasText:'Семьи'}).click();
 await page.getByRole('heading',{name:'Семьи.'}).waitFor();
 assert.equal(await page.locator('.family-card').count(),5);
 await page.getByRole('button',{name:'Новая семья'}).click();
 await page.getByRole('dialog').waitFor();
 await page.locator('[name="name"]').fill('Проверка формы');
 await page.getByRole('button',{name:'Отмена',exact:true}).click();
 await page.locator('.family-card').first().click();
 await page.getByRole('heading',{name:'Аккаунт владельца'}).waitFor();
 assert.equal(await page.locator('#owner-password').count(),1);
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.getByRole('button',{name:'Записать продление и расход'}).click();
 assert.equal(await page.locator('[name="paid_until"]').count(),0);
 await page.locator('[name="months"]').fill('3');
 assert.match(await page.locator('.renewal-preview').textContent(),/3 мес/);
 await page.screenshot({path:'test-results/renewal-months.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Отмена',exact:true}).click();
 await page.getByRole('button',{name:'Добавить участника',exact:true}).click();
 assert.equal(await page.locator('[name="vpn_price"]').count(),0);
 assert.equal(await page.locator('[name="spotify_price"]').count(),1);
 assert.equal(await page.locator('[name="is_owner"]').isDisabled(),true);
 await page.locator('[name="needs_vpn"]').check();
 assert.equal(await page.locator('[name="vpn_price"]').count(),1);
 await page.locator('[name="is_free"]').check();
 assert.equal(await page.locator('[name="spotify_price"]').count(),0);
 assert.equal(await page.locator('[name="vpn_price"]').count(),0);
 await page.locator('[name="is_free"]').uncheck();
 assert.equal(await page.locator('[name="spotify_price"]').count(),1);
 assert.equal(await page.locator('[name="vpn_price"]').count(),1);
 await page.getByRole('button',{name:'Отмена',exact:true}).click();
 await page.screenshot({path:'test-results/family-detail.png',fullPage:true,animations:'disabled'});
 await page.locator('.nav-item').filter({hasText:'Участники'}).click();
 await page.getByRole('heading',{name:'Участники.'}).waitFor();
 await page.getByRole('textbox',{name:'Имя или почта'}).fill('Вера');
 assert.equal(await page.locator('tbody tr').count(),1);
 await page.getByRole('button',{name:'Редактировать: Вера'}).click();
 await page.getByRole('dialog').waitFor();
 await page.screenshot({path:'test-results/member-dialog.png',fullPage:true,animations:'disabled'});
 await page.keyboard.press('Escape');
 await page.locator('.nav-item').filter({hasText:'Платежи'}).click();
 await page.getByRole('button',{name:'Добавить оплату',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.locator('[name="months"]').fill('3');
 assert.equal(await page.locator('[name="amount"]').inputValue(),'36');
 assert.match(await page.locator('.payment-preview').textContent(),/Период:/);
 await page.getByRole('button',{name:'Отмена',exact:true}).click();
 for(const name of ['VPN и серверы','Финансы','Настройки']){
   await page.locator('.nav-item').filter({hasText:name}).click();
   await page.getByRole('heading',{name:name+'.',exact:true}).waitFor();
 }
 await page.getByRole('button',{name:'Изменить курс USD'}).click();
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Меню',exact:true}).click();
 await page.locator('.nav-item').filter({hasText:'Обзор'}).click();
 await page.getByRole('heading',{name:'Твои подписки.'}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
 await page.screenshot({path:'test-results/mobile-light.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Включить тёмную тему'}).click();
 await page.screenshot({path:'test-results/mobile-dark.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Меню',exact:true}).click();
 await page.locator('.nav-item').filter({hasText:'Семьи'}).click();
 await page.getByRole('button',{name:'Новая семья'}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'test-results/mobile-form.png',fullPage:true,animations:'disabled'});
 await page.keyboard.press('Escape');
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed: desktop/mobile, both themes, currency, navigation, search, forms, payment preview, no page errors or horizontal overflow. No business records modified.');
}finally{await browser.close();}
