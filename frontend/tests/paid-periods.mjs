import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://localhost:3000');
 await page.getByRole('button',{name:'Открыть локальную версию'}).click();
 await page.getByRole('heading',{name:'Твои подписки.'}).waitFor();
 await page.locator('.nav-item').filter({hasText:'Участники'}).click();
 await page.getByRole('button',{name:'Редактировать: Вера',exact:true}).click();
 await page.getByRole('button',{name:'Учесть прежнюю оплату',exact:true}).click();
 await page.getByRole('heading',{name:'Учесть прежнюю оплату',exact:true}).waitFor();
 await page.locator('[name="paid_until"]').fill('2027-11-29');
 await page.locator('[name="note"]').fill('Оплачено до начала учёта');
 await page.screenshot({path:'test-results/paid-period-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'test-results/paid-period-mobile.png',fullPage:true});
 let adjustment;
 await page.route('**/api/members/*/paid-period/',async route=>{adjustment=route.request().postDataJSON();await route.fulfill({status:200,contentType:'application/json',body:'{}'});});
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 assert.deepEqual(adjustment,{service:'spotify',paid_until:'2027-11-29',note:'Оплачено до начала учёта'});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'Добавить участника',exact:true}).click();
 await page.locator('[name="name"]').fill('Existing participant');
 await page.locator('[name="email"]').fill('existing@example.com');
 await page.locator('[name="joined_on"]').fill('2025-10-29');
 await page.locator('[name="spotify_until"]').fill('2027-11-29');
 assert.equal(await page.locator('[name="vpn_until"]').count(),0);
 await page.locator('[name="needs_vpn"]').check();
 assert.equal(await page.locator('[name="vpn_until"]').count(),1);
 await page.locator('[name="is_free"]').check();
 assert.equal(await page.locator('[name="spotify_until"]').count(),0);
 await page.locator('[name="is_free"]').uncheck();
 await page.screenshot({path:'test-results/import-member.png',fullPage:true});
 let member;
 await page.route('**/api/members/',async route=>{if(route.request().method()==='POST'){member=route.request().postDataJSON();await route.fulfill({status:201,contentType:'application/json',body:'{}'});}else await route.continue();});
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 assert.equal(member.joined_on,'2025-10-29');assert.equal(member.spotify_until,'2027-11-29');assert.ok(!('vpn_until' in member));
 assert.deepEqual(errors,[]);
 console.log('Paid-period forms passed: import dates, correction payload, responsive dialog, conditional VPN/free fields. Writes intercepted; no business data modified.');
}finally{await browser.close();}
